"""Turn the original cover images in covers-source/ into uniform square web covers.

    python3 scripts/process-covers.py

Input:  covers-source/NNN-<game-id>.<ext>   (any size or shape)
Output: public/covers/<game-id>.webp        (600x600) and src/data/localCovers.ts

Near-square images are centre-cropped. Anything else is fitted whole (no title is cut off)
over a blurred, darkened copy of itself, so every cover has the same size and framing.
Requires Pillow.
"""
from pathlib import Path

from PIL import Image, ImageEnhance, ImageFilter, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'covers-source'
OUT = ROOT / 'public' / 'covers'
SIZE = 600
CROP_TOLERANCE = 0.06  # crop only when the aspect ratio is within 6% of square


def square(im: Image.Image) -> Image.Image:
    w, h = im.size
    if abs(w / h - 1) <= CROP_TOLERANCE:
        return ImageOps.fit(im, (SIZE, SIZE), Image.LANCZOS)
    backdrop = ImageOps.fit(im, (SIZE, SIZE), Image.LANCZOS).filter(ImageFilter.GaussianBlur(28))
    backdrop = ImageEnhance.Brightness(backdrop).enhance(0.45)
    fg = ImageOps.contain(im, (SIZE, SIZE), Image.LANCZOS)
    backdrop.paste(fg, ((SIZE - fg.width) // 2, (SIZE - fg.height) // 2))
    return backdrop


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    ids = []
    for path in sorted(SRC.iterdir()):
        if path.name.startswith('.'):
            continue
        game_id = path.stem.split('-', 1)[1]
        im = ImageOps.exif_transpose(Image.open(path)).convert('RGB')
        square(im).save(OUT / f'{game_id}.webp', quality=84, method=6)
        ids.append(game_id)
    lines = ',\n'.join(f"  '{i}'" for i in ids)
    (ROOT / 'src' / 'data' / 'localCovers.ts').write_text(
        '// Generated by scripts/process-covers.py — games with a local cover in public/covers/.\n'
        f'export const LOCAL_COVERS = new Set<string>([\n{lines},\n]);\n'
    )
    print(f'{len(ids)} covers written to {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
